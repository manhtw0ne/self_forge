CREATE TABLE goal_habit_plan (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
 goal_id BIGINT NOT NULL,
 habit_id BIGINT NOT NULL,
 request_id VARCHAR(36) NOT NULL,
 CONSTRAINT ux_goal_habit_request UNIQUE (user_id, request_id)
);
-- Retain the application receipt if a source goal is deleted; never recreate a habit on retry.
CREATE INDEX ix_goal_habit_owner_goal ON goal_habit_plan(user_id, goal_id);
