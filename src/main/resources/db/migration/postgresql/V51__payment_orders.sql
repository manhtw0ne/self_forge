CREATE TABLE payment_order (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(id) ON DELETE RESTRICT,
    plan VARCHAR(16) NOT NULL,
    status VARCHAR(16) NOT NULL,
    amount_vnd BIGINT NOT NULL,
    currency VARCHAR(3) NOT NULL,
    reference VARCHAR(32) NOT NULL UNIQUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    paid_at TIMESTAMP WITH TIME ZONE,
    entitlement_expires_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT ck_payment_order_plan CHECK (plan IN ('MONTHLY', 'YEARLY', 'LIFETIME')),
    CONSTRAINT ck_payment_order_status CHECK (status IN ('PENDING', 'PAID', 'EXPIRED', 'CANCELLED', 'REVIEW', 'REFUNDED')),
    CONSTRAINT ck_payment_order_amount_vnd CHECK (amount_vnd > 0),
    CONSTRAINT ck_payment_order_currency CHECK (currency = 'VND'),
    CONSTRAINT ck_payment_order_expiry CHECK (expires_at > created_at)
);

CREATE INDEX ix_payment_order_user_created_at ON payment_order (user_id, created_at DESC);
CREATE INDEX ix_payment_order_status_expires_at ON payment_order (status, expires_at);

CREATE TABLE payment_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_order_id BIGINT REFERENCES payment_order(id) ON DELETE SET NULL,
    provider VARCHAR(32) NOT NULL,
    external_id VARCHAR(128) NOT NULL,
    order_reference VARCHAR(32),
    amount_vnd BIGINT NOT NULL,
    disposition VARCHAR(16) NOT NULL,
    review_reason VARCHAR(32),
    received_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ux_payment_event_provider_external UNIQUE (provider, external_id),
    CONSTRAINT ck_payment_event_amount_vnd CHECK (amount_vnd > 0),
    CONSTRAINT ck_payment_event_disposition CHECK (disposition IN ('ACCEPTED', 'REVIEW')),
    CONSTRAINT ck_payment_event_review_reason CHECK (review_reason IS NULL OR review_reason IN
        ('UNMATCHED_REFERENCE', 'INELIGIBLE_TRANSFER', 'ORDER_NOT_PAYABLE', 'AMOUNT_MISMATCH', 'LIFETIME_ALREADY_ACTIVE'))
);

CREATE INDEX ix_payment_event_order_received_at ON payment_event (payment_order_id, received_at DESC);
