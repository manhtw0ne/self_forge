-- A small user-visible account activity trail. No IP address, device fingerprint, token,
-- email, password, OTP, or user-authored content is retained here.
create table account_security_event (
    id bigint generated by default as identity,
    user_id bigint not null,
    event_type varchar(40) not null check (event_type in (
        'REGISTERED', 'SIGNED_IN', 'SIGNED_IN_WITH_OAUTH', 'PASSWORD_CHANGED',
        'PASSWORD_RESET', 'SESSION_REVOKED', 'OTHER_SESSIONS_REVOKED'
    )),
    occurred_at timestamp(6) with time zone not null,
    primary key (id)
);

alter table account_security_event add constraint fk_account_security_event_user_id
    foreign key (user_id) references app_user;

create index idx_account_security_event_user_id_id on account_security_event (user_id, id desc);
