CREATE TABLE habit_batch_receipt (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
    request_id VARCHAR(36) NOT NULL,
    fingerprint VARCHAR(64) NOT NULL,
    habit_ids VARCHAR(255) NOT NULL,
    CONSTRAINT ux_habit_batch_request UNIQUE (user_id, request_id)
);
-- Keep original IDs after habits are deactivated; replay must never reactivate them.
