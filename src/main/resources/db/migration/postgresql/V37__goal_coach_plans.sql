CREATE TABLE goal_coach_plan (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
    goal_id BIGINT NOT NULL REFERENCES goal(id) ON DELETE CASCADE,
    language VARCHAR(2) NOT NULL,
    evidence_fingerprint VARCHAR(64) NOT NULL,
    headline VARCHAR(280) NOT NULL,
    steps_json TEXT NOT NULL,
    habits_json TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_goal_coach_plan_language CHECK (language IN ('vi', 'en')),
    CONSTRAINT uq_goal_coach_plan_snapshot UNIQUE (user_id, goal_id, language, evidence_fingerprint)
);

CREATE INDEX ix_goal_coach_plan_user_goal ON goal_coach_plan (user_id, goal_id);
