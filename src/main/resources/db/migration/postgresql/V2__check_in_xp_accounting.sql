-- Preserve legacy rows as unknown; do not guess XP from today's habit points.
alter table daily_check_in add column points_snapshot integer;
alter table daily_check_in add column failure_points_snapshot integer;
alter table daily_check_in add column applied_xp integer;

create table check_in_xp_adjustment (
    id bigint generated by default as identity primary key,
    check_in_id bigint not null references daily_check_in(id),
    from_status varchar(255),
    to_status varchar(255),
    delta integer not null,
    created_at timestamp(6) with time zone
);
create index idx_check_in_xp_adjustment_source on check_in_xp_adjustment(check_in_id);

alter table penalty add column check_in_id bigint references daily_check_in(id);
alter table penalty add column reversed boolean not null default false;
create index idx_penalty_check_in on penalty(check_in_id);
