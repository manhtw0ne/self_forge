CREATE TABLE feedback_submission (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
    feedback_type VARCHAR(16) NOT NULL,
    summary VARCHAR(500) NOT NULL,
    steps TEXT NOT NULL,
    expected_result TEXT NOT NULL,
    language VARCHAR(2) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_feedback_submission_type CHECK (feedback_type IN ('BUG', 'IDEA', 'OTHER')),
    CONSTRAINT ck_feedback_submission_language CHECK (language IN ('vi', 'en'))
);

CREATE INDEX ix_feedback_submission_user_id_id ON feedback_submission (user_id, id DESC);
CREATE INDEX ix_feedback_submission_user_created_at ON feedback_submission (user_id, created_at);
