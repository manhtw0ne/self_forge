CREATE TABLE ai_coach_usage (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
    usage_month DATE NOT NULL,
    feature VARCHAR(24) NOT NULL,
    request_count INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT ck_ai_coach_usage_feature CHECK (feature IN ('WEEKLY', 'GOAL', 'RESTART')),
    CONSTRAINT ck_ai_coach_usage_count CHECK (request_count >= 0),
    CONSTRAINT uq_ai_coach_usage_user_month_feature UNIQUE (user_id, usage_month, feature)
);

CREATE INDEX ix_ai_coach_usage_month ON ai_coach_usage (usage_month);
