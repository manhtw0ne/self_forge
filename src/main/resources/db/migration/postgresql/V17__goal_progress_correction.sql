CREATE TABLE goal_progress_correction (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 goal_id BIGINT NOT NULL REFERENCES goal(id) ON DELETE CASCADE,
 from_value INTEGER NOT NULL CHECK (from_value >= 0),
 to_value INTEGER NOT NULL CHECK (to_value >= 0),
 target_value INTEGER NOT NULL CHECK (target_value > 0),
 unit VARCHAR(255) NOT NULL,
 from_status VARCHAR(16) NOT NULL CHECK (from_status IN ('ACTIVE','COMPLETED')),
 to_status VARCHAR(16) NOT NULL CHECK (to_status IN ('ACTIVE','COMPLETED')),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX goal_progress_correction_history ON goal_progress_correction(goal_id,id);
