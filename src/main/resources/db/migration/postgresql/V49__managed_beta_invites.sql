CREATE TABLE beta_invite (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code_hash VARCHAR(64) NOT NULL UNIQUE,
    label VARCHAR(100) NOT NULL DEFAULT '',
    max_uses INTEGER NOT NULL,
    use_count INTEGER NOT NULL DEFAULT 0,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    expires_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    revoked_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT ck_beta_invite_max_uses CHECK (max_uses BETWEEN 1 AND 1000),
    CONSTRAINT ck_beta_invite_use_count CHECK (use_count BETWEEN 0 AND max_uses)
);

CREATE INDEX ix_beta_invite_active_expires_at ON beta_invite (active, expires_at);
