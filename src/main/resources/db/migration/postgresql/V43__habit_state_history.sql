-- Start collecting observed state changes without backfilling unknown legacy dates.
CREATE TABLE habit_state_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    habit_id BIGINT NOT NULL REFERENCES habit(id) ON DELETE CASCADE,
    kind VARCHAR(16) NOT NULL CHECK (kind IN ('CREATED', 'OBSERVED', 'CHANGED')),
    target_per_week INTEGER NOT NULL CHECK (target_per_week BETWEEN 1 AND 7),
    active BOOLEAN NOT NULL,
    recorded_at TIMESTAMP WITH TIME ZONE NOT NULL,
    calendar_date DATE NOT NULL,
    timezone VARCHAR(64) NOT NULL
);
CREATE INDEX idx_habit_state_history_habit_id_id ON habit_state_history(habit_id, id DESC);
