CREATE TABLE companion_milestone_ack (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
    stage INTEGER NOT NULL CHECK (stage IN (2, 3)),
    acknowledged_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ux_companion_milestone_ack_user_stage UNIQUE (user_id, stage)
);

CREATE INDEX idx_companion_milestone_ack_user_stage ON companion_milestone_ack(user_id, stage);

-- Existing visible companions previously used a browser-only baseline. Mark
-- milestones they had already reached as seen so this release does not replay
-- celebrations merely because the acknowledgement became account-synchronised.
INSERT INTO companion_milestone_ack (user_id, stage, acknowledged_at)
SELECT preference.user_id, 2, CURRENT_TIMESTAMP
FROM companion_preference preference
WHERE preference.visible = TRUE AND COALESCE((
    SELECT SUM(entry.points_snapshot)
    FROM daily_check_in entry
    JOIN habit habit ON habit.id = entry.habit_id
    WHERE habit.user_id = preference.user_id
      AND entry.status = 'COMPLETED'
      AND entry.points_snapshot > 0
      AND entry.applied_xp IS NOT NULL
), 0) >= 100;

INSERT INTO companion_milestone_ack (user_id, stage, acknowledged_at)
SELECT preference.user_id, 3, CURRENT_TIMESTAMP
FROM companion_preference preference
WHERE preference.visible = TRUE AND COALESCE((
    SELECT SUM(entry.points_snapshot)
    FROM daily_check_in entry
    JOIN habit habit ON habit.id = entry.habit_id
    WHERE habit.user_id = preference.user_id
      AND entry.status = 'COMPLETED'
      AND entry.points_snapshot > 0
      AND entry.applied_xp IS NOT NULL
), 0) >= 500;
