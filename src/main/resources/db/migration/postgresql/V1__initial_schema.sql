create table achievement (
    xp_reward integer not null,
    id bigint generated by default as identity,
    code varchar(255) not null unique,
    description varchar(255),
    icon_emoji varchar(255),
    name varchar(255) not null,
    primary key (id)
);

create table app_user (
    created_at timestamp(6) with time zone,
    id bigint generated by default as identity,
    premium_expires_at timestamp(6) with time zone,
    avatar_url varchar(255),
    display_name varchar(255) not null,
    email varchar(255) not null unique,
    motto varchar(255),
    password_hash varchar(255) not null,
    premium_tier varchar(255) not null check (premium_tier in ('FREE','PREMIUM','LIFETIME')),
    timezone varchar(255),
    primary key (id)
);

create table auth_session (
    created_at timestamp(6) with time zone,
    expires_at timestamp(6) with time zone,
    id bigint generated by default as identity,
    user_id bigint not null,
    token_hash varchar(64) not null unique,
    primary key (id)
);

create table category (
    created_at timestamp(6) with time zone,
    id bigint generated by default as identity,
    user_id bigint,
    color varchar(255),
    icon varchar(255),
    name varchar(255) not null,
    primary key (id)
);

create table challenge (
    end_date date,
    start_date date,
    target_days integer not null check (target_days>=1),
    created_at timestamp(6) with time zone,
    habit_id bigint not null,
    id bigint generated by default as identity,
    user_id bigint not null,
    description varchar(255),
    name varchar(255) not null,
    status varchar(255) check (status in ('ACTIVE','COMPLETED','ABANDONED')),
    primary key (id)
);

create table custom_reward (
