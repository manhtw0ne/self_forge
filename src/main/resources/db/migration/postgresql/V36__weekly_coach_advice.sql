CREATE TABLE weekly_coach_advice (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
    week_start DATE NOT NULL,
    language VARCHAR(2) NOT NULL,
    evidence_fingerprint VARCHAR(64) NOT NULL,
    headline VARCHAR(280) NOT NULL,
    observations_json TEXT NOT NULL,
    experiments_json TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_weekly_coach_advice_language CHECK (language IN ('vi', 'en')),
    CONSTRAINT uq_weekly_coach_advice_snapshot UNIQUE (user_id, week_start, language, evidence_fingerprint)
);

CREATE INDEX ix_weekly_coach_advice_user_week ON weekly_coach_advice (user_id, week_start);
