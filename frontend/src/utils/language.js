export function normalizeLanguage(value) {
  if (typeof value !== 'string') return null;
  const base = value.toLowerCase().split('-')[0];
  return ['vi', 'en'].includes(base) ? base : null;
}

export function initialLanguage(storage, browserLanguage = 'vi') {
  try {
    const saved = normalizeLanguage(storage?.getItem('sf_language'));
    if (saved) return saved;
  } catch { /* Storage can be blocked; switching languages still works in memory. */ }
  return normalizeLanguage(browserLanguage) ?? 'vi';
}

// A language selected before authentication belongs to the person only after
// they deliberately sign in or register. An existing account setting always
// wins, so opening a public page cannot overwrite another device's choice.
export function pendingAccountLanguage(accountLanguage, explicitPublicLanguage) {
  if (normalizeLanguage(accountLanguage)) return null;
  return normalizeLanguage(explicitPublicLanguage);
}

export function translate(language, source, parameters = {}) {
  const needsEnglishFallback = language === 'en' && !Object.hasOwn(english, source) && /[À-ỹ]/.test(source);
  // API details are translated by the same function as interface copy. New
  // backend validations must never leave an English user with an unexplained
  // Vietnamese error while a precise translation is being added.
  const template = language === 'en'
    ? (Object.hasOwn(english, source) ? english[source] : needsEnglishFallback ? 'We could not complete this action. Review your input and try again.' : source)
    : source;
  return template.replace(/\{(\w+)\}/g, (placeholder, key) =>
    Object.hasOwn(parameters, key) ? String(parameters[key]) : placeholder);
}

export function localizedCategory(language, category) {
  if (!category) return undefined;
  return category.systemDefault ? translate(language, category.name) : category.name;
}
